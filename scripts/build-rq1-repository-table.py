"""Generate per-repository rows from the same audited values as the bundler table."""
from pathlib import Path
import json
ROOT=Path(__file__).resolve().parents[1]
report=json.loads((ROOT/'manuscript/data/rq1-bundler-breakdown.json').read_text())
index=json.loads((ROOT.parent/'ReCall Dataset/qualified-dataset/index.json').read_text())
subjects={r['subject']:r for r in index['subjects']}
order=['webpack','vite','esbuild','rollup','turbopack','parcel','bun']
names=dict(zip(order,['Webpack','Vite','esbuild','Rollup','Turbopack','Parcel','Bun']))
assert len(report['subjects'])==len(subjects)==35
for group in order:
 assert sum(subjects[r['subject']]['libraryCount'] for r in report['subjects'] if r['subject'].startswith(group+'/'))==report['byBundler'][group]['libraries']
def hms(s):
 h,t=divmod(round(s),3600);m,s=divmod(t,60);return f'{h:02}:{m:02}:{s:02}'
def escape(s):return s.replace('_',r'\_').replace('&',r'\&').replace('-',r'-\allowbreak ')
header=r'''\toprule
\multirow{3}{*}{\shortstack{\textbf{Bundler}\\\textbf{Group}}} & \multirow{3}{*}{\textbf{Repo}} & \multicolumn{4}{c}{\textbf{Precision (\%)}} & \multirow{3}{*}{\shortstack{\textbf{Recovery}\\\textbf{(\%)}}} & \multicolumn{2}{c}{\textbf{Process time}} \\
\cmidrule(lr){3-6}\cmidrule(l){8-9}
 & & \shortstack{POG\\Match} & \shortstack{AST\\Match} & \shortstack{Model\\Validation} & Overall & & \shortstack{Total\\(h:min:s)} & \shortstack{Per Lib\\(min)} \\
\midrule
'''
tex=r'''% Generated by scripts/build-rq1-repository-table.py.
\begingroup
\small
\setlength{\tabcolsep}{2pt}
\renewcommand{\arraystretch}{1.12}
\setlength{\LTleft}{\fill}
\setlength{\LTright}{\fill}
\begin{longtable}{@{}l>{\raggedright\arraybackslash}p{25mm}ccccccc@{}}
\caption{ReCall's recovery accuracy and estimated process time by repository. Repository names omit the owner; metrics and timing follow Table~\ref{tab:rq1-bundler-breakdown}. A dash indicates no assessed mappings for that stage.}\label{tab:rq1-repository-breakdown}\\
'''+header+r'''\endfirsthead
\multicolumn{9}{c}{\tablename~\thetable{} (continued)}\\
'''+header+r'''\endhead
\midrule
\multicolumn{9}{r}{Continued on next page}\\
\endfoot
\bottomrule
\endlastfoot
'''
records=[]
for i,group in enumerate(order):
 if i:tex+=r'\midrule'+'\n'
 for r in sorted([r for r in report['subjects'] if r['subject'].startswith(group+'/')],key=lambda r:subjects[r['subject']]['repo'].split('/')[-1].lower()):
  entry=subjects[r['subject']];st=r['stages'];n=entry['libraryCount'];assert st['Overall']['denominator']==entry['oneToOnePairs']
  prec=[f"{100*st[k]['correct']/st[k]['assessedPredictions']:.2f}" if st[k]['assessedPredictions'] else '---' for k in ['POG','AST','Validation','Overall']]
  vals=[names[group],escape(entry['repo'].split('/')[-1])]+prec+[f"{100*st['Overall']['correct']/st['Overall']['denominator']:.2f}",hms(r['processSeconds']),f"{r['processSeconds']/60/n:.2f}"]
  tex+=' & '.join(vals)+r' \\'+'\n'
  records.append(dict(subject=r['subject'],libraries=n,values=vals))
tex+=r'\end{longtable}\endgroup'+'\n'
(ROOT/'manuscript/data/rq1-repository-breakdown.tex').write_text(tex)
(ROOT/'manuscript/data/rq1-repository-breakdown.json').write_text(json.dumps(records,indent=2)+'\n')
print('Generated',len(records),'repository rows; library counts reconcile with all seven groups.')
